-- 公开账户与个人观影数据。请在Supabase SQL Editor中完整执行一次。
-- 所有公开表均启用RLS，匿名访问者没有读写权限。

create table if not exists public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null check (char_length(display_name) between 1 and 40),
  model_user_id integer not null check (model_user_id between 1 and 943),
  favorite_genres text[] not null default '{}',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.account_interactions (
  id bigint generated by default as identity primary key,
  account_id uuid not null references auth.users(id) on delete cascade,
  model_user_id integer not null check (model_user_id between 1 and 943),
  movie_id integer not null check (movie_id between 1 and 1682),
  status text not null check (status in ('want_to_watch', 'watched')),
  personal_rating double precision check (personal_rating is null or personal_rating between 1 and 5),
  feedback text check (feedback is null or feedback in ('like', 'neutral', 'dislike', 'not_interested')),
  note text not null default '' check (char_length(note) <= 500),
  predicted_rating double precision check (predicted_rating is null or predicted_rating between 1 and 5),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (account_id, movie_id)
);

create table if not exists public.account_catalog_interactions (
  id bigint generated by default as identity primary key,
  account_id uuid not null references auth.users(id) on delete cascade,
  catalog_id text not null,
  status text not null check (status in ('want_to_watch', 'watched')),
  personal_rating double precision check (personal_rating is null or personal_rating between 1 and 5),
  note text not null default '' check (char_length(note) <= 500),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (account_id, catalog_id)
);

create index if not exists profiles_user_id_idx on public.profiles(user_id);
create index if not exists account_interactions_account_id_idx on public.account_interactions(account_id);
create index if not exists account_catalog_interactions_account_id_idx on public.account_catalog_interactions(account_id);

alter table public.profiles enable row level security;
alter table public.account_interactions enable row level security;
alter table public.account_catalog_interactions enable row level security;

revoke all on table public.profiles from anon, authenticated;
revoke all on table public.account_interactions from anon, authenticated;
revoke all on table public.account_catalog_interactions from anon, authenticated;
grant select, insert, update, delete on table public.profiles to authenticated;
grant select, insert, update, delete on table public.account_interactions to authenticated;
grant select, insert, update, delete on table public.account_catalog_interactions to authenticated;
grant usage, select on all sequences in schema public to authenticated;

drop policy if exists "profiles_select_own" on public.profiles;
drop policy if exists "profiles_insert_own" on public.profiles;
drop policy if exists "profiles_update_own" on public.profiles;
drop policy if exists "profiles_delete_own" on public.profiles;
drop policy if exists "interactions_select_own" on public.account_interactions;
drop policy if exists "interactions_insert_own" on public.account_interactions;
drop policy if exists "interactions_update_own" on public.account_interactions;
drop policy if exists "interactions_delete_own" on public.account_interactions;
drop policy if exists "catalog_interactions_select_own" on public.account_catalog_interactions;
drop policy if exists "catalog_interactions_insert_own" on public.account_catalog_interactions;
drop policy if exists "catalog_interactions_update_own" on public.account_catalog_interactions;
drop policy if exists "catalog_interactions_delete_own" on public.account_catalog_interactions;

create policy "profiles_select_own" on public.profiles for select to authenticated
  using ((select auth.uid()) = user_id);
create policy "profiles_insert_own" on public.profiles for insert to authenticated
  with check ((select auth.uid()) = user_id);
create policy "profiles_update_own" on public.profiles for update to authenticated
  using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
create policy "profiles_delete_own" on public.profiles for delete to authenticated
  using ((select auth.uid()) = user_id);

create policy "interactions_select_own" on public.account_interactions for select to authenticated
  using ((select auth.uid()) = account_id);
create policy "interactions_insert_own" on public.account_interactions for insert to authenticated
  with check ((select auth.uid()) = account_id);
create policy "interactions_update_own" on public.account_interactions for update to authenticated
  using ((select auth.uid()) = account_id) with check ((select auth.uid()) = account_id);
create policy "interactions_delete_own" on public.account_interactions for delete to authenticated
  using ((select auth.uid()) = account_id);

create policy "catalog_interactions_select_own" on public.account_catalog_interactions for select to authenticated
  using ((select auth.uid()) = account_id);
create policy "catalog_interactions_insert_own" on public.account_catalog_interactions for insert to authenticated
  with check ((select auth.uid()) = account_id);
create policy "catalog_interactions_update_own" on public.account_catalog_interactions for update to authenticated
  using ((select auth.uid()) = account_id) with check ((select auth.uid()) = account_id);
create policy "catalog_interactions_delete_own" on public.account_catalog_interactions for delete to authenticated
  using ((select auth.uid()) = account_id);
